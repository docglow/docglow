import type { ProjectTest, TestsData, TestSummary } from '../types'

/**
 * Count of tests that broke the build on the last run: hard failures plus
 * errors (a `warn`-severity result is intentionally excluded — it did not
 * fail). Drives the red count on the sidebar Tests badge.
 */
export function failingTestCount(summary: TestSummary): number {
  return summary.by_status.fail + summary.by_status.error
}

/**
 * Whether a test row has anything to reveal when expanded — a failure/warn
 * message from the run, or at least the file it was defined in. Passing tests
 * with no message still expand to show provenance.
 */
export function testRowHasDetail(test: ProjectTest): boolean {
  return Boolean(test.message) || test.original_file_path !== ''
}

/** What the sidebar's Tests entry shows next to its label. */
export type TestsNavBadge = { readonly kind: 'fail'; readonly count: number } | { readonly kind: 'pass' }

/**
 * Sidebar badge for the Tests entry. A failure count wins; the green check is
 * only a claim that tests *ran* and nothing failed, so it needs run results
 * and at least one test that actually ran. Defined-but-not-run tests get no
 * badge, matching the page, which reports them as not run rather than passing.
 */
export function testsNavBadge(summary: TestSummary): TestsNavBadge | null {
  const failing = failingTestCount(summary)
  if (failing > 0) return { kind: 'fail', count: failing }
  const ran = summary.total - summary.by_status.not_run
  if (summary.has_run_results && ran > 0) return { kind: 'pass' }
  return null
}

/**
 * Why the Tests page has nothing to list, if it has nothing.
 *
 * - `legacy`: the payload has no `tests` key — it was generated by a Docglow
 *   version that predates the Tests page. The project may well have tests.
 * - `none`: the payload has the key and the project defines no tests (in this
 *   site — `--select` / `--exclude` can narrow it to zero).
 */
export type TestsEmptyState = 'legacy' | 'none'

export function testsEmptyState(tests: TestsData | undefined): TestsEmptyState | null {
  if (tests === undefined) return 'legacy'
  if (tests.tests.length === 0) return 'none'
  return null
}
